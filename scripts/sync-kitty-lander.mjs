// Copies the Kitty Lander Unity Web build into public/games/kitty-lander/ and refreshes
// the matching Cloudflare Pages header rules in public/_headers.
//
// Usage:  npm run sync:kitty-lander
//         KITTY_LANDER_BUILD="D:/path/to/Builds/Web" npm run sync:kitty-lander
//
// Source: the folder Unity writes with "Kitty Lander > Build Web (Cloudflare Pages)".
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(fileURLToPath(new URL('..', import.meta.url)))
const source = resolve(process.env.KITTY_LANDER_BUILD ?? join(root, '..', 'Unity Projects', 'kitty-lander', 'Builds', 'Web'))
const target = join(root, 'public', 'games', 'kitty-lander')
const headersFile = join(root, 'public', '_headers')
const BEGIN = '# BEGIN kitty-lander (generated by scripts/sync-kitty-lander.mjs - do not edit by hand)'
const END = '# END kitty-lander'

if (!existsSync(join(source, 'Build')) || !existsSync(join(source, 'index.html'))) {
  console.error(`No Unity Web build found at ${source}\nBuild it in Unity (Kitty Lander > Build Web) or set KITTY_LANDER_BUILD.`)
  process.exit(1)
}

// 1. copy index.html + Build/ (replace the old Build folder completely)
rmSync(join(target, 'Build'), { recursive: true, force: true })
mkdirSync(join(target, 'Build'), { recursive: true })
copyFileSync(join(source, 'index.html'), join(target, 'index.html'))
const files = readdirSync(join(source, 'Build')).sort()
let total = 0
for (const f of files) {
  copyFileSync(join(source, 'Build', f), join(target, 'Build', f))
  const size = statSync(join(source, 'Build', f)).size
  total += size
  if (size > 25 * 1024 * 1024) console.warn(`WARNING: ${f} is over Cloudflare Pages' 25 MiB file limit`)
}

// 2. header rules: Unity's pre-compressed .br files need Content-Encoding: br
const contentType = (name) =>
  name.endsWith('.wasm') ? 'application/wasm'
  : name.endsWith('.js') ? 'application/javascript'
  : name.endsWith('.json') ? 'application/json'
  : 'application/octet-stream'
const rules = [BEGIN]
for (const f of files) {
  rules.push(`/games/kitty-lander/Build/${f}`)
  if (f.endsWith('.br')) {
    rules.push('  Content-Encoding: br')
    rules.push(`  Content-Type: ${contentType(f.slice(0, -3))}`)
  } else {
    rules.push(`  Content-Type: ${contentType(f)}`)
  }
}
rules.push(END)
const block = rules.join('\n')
let headers = readFileSync(headersFile, 'utf8')
const start = headers.indexOf(BEGIN)
const end = headers.indexOf(END)
headers = start >= 0 && end > start
  ? headers.slice(0, start) + block + headers.slice(end + END.length)
  : headers.trimEnd() + '\n\n' + block + '\n'
writeFileSync(headersFile, headers)

console.log(`Copied ${files.length} build files (${(total / 1048576).toFixed(2)} MB) from\n  ${source}\nto\n  ${target}`)
console.log('Updated Cloudflare header rules in public/_headers')
